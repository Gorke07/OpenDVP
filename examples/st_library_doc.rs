//! Prints the ST standard library reference as Markdown (from the `(*! *)` doc comments).
//!
//! ```powershell
//! cargo run --example st_library_doc > docs/st-library.md
//! ```
use opendvp::st::{LibraryParam, library_entries, library_errors};

fn params(list: &[LibraryParam]) -> String {
    if list.is_empty() {
        return "—".into();
    }
    list.iter()
        .map(|p| format!("`{}` {}", p.name, p.ty))
        .collect::<Vec<_>>()
        .join(", ")
}

fn main() {
    let errors = library_errors();
    assert!(errors.is_empty(), "library files failed to parse: {errors:?}");
    let entries = library_entries();
    println!("# OpenDVP ST standard library\n");
    println!(
        "Generated by `cargo run --example st_library_doc` from `src/st/stdlib/*.st`. \
         {} blocks. Every ST program can use them without declaring them; only blocks a \
         program uses are compiled into it. A program may define its own block with the same \
         name, which then replaces the library block.\n",
        entries.len()
    );
    let mut category = "";
    for e in &entries {
        if e.category != category {
            category = e.category;
            println!("## {}\n", category);
            for x in entries.iter().filter(|x| x.category == category) {
                println!("- [`{}`](#{})", x.name, x.name.to_lowercase());
            }
            println!();
        }
        println!("### {}\n", e.name);
        let signature = match &e.returns {
            Some(t) => format!("FUNCTION {} : {t}", e.name),
            None => format!("FUNCTION_BLOCK {}", e.name),
        };
        println!("`{signature}`\n");
        // Keep the comment's line breaks (Markdown hard breaks).
        println!("{}\n", e.doc.replace('\n', "  \n"));
        println!("- Inputs: {}", params(&e.inputs));
        if e.returns.is_none() {
            println!("- Outputs: {}", params(&e.outputs));
        }
        println!();
    }
}
